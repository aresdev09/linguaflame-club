"""Ошибки клиента ИИ.

Иерархия повторяет логику повторов: сетевые сбои и 5xx/429 имеет смысл
повторить, таймаут — нет (повтор только удлинит ожидание), 4xx — нет
(сервер отклонил запрос), невалидный ответ — да (модель могла ошибиться).
"""


class AIError(RuntimeError):
    """Базовая ошибка общения с ИИ-сервером."""


class AIRequestError(AIError):
    """Сеть, 5xx или 429 — запрос повторяется."""


class AITimeoutError(AIRequestError):
    """Модель не ответила за отведённое время."""


class AIRequestRejected(AIError):
    """Сервер отклонил запрос (4xx) — повтор не поможет."""


class AIResponseError(AIError):
    """Ответ не разобрался или не прошёл схему — запрос повторяется."""
